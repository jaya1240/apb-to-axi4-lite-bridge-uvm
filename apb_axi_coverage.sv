// apb_axi_coverage.sv
//
// Functional coverage on observed traffic:
//   cg_apb : what the APB side actually did (direction, address region,
//            strobe pattern, PSLVERR, wait states, idle gap) and the
//            crosses that matter (direction x error, direction x idle).
//   cg_axi : what the AXI side actually saw/returned (direction x
//            response code) -- confirms error injection genuinely
//            reached the bus, not just that it was configured.

class apb_axi_coverage extends uvm_component;
    `uvm_component_utils(apb_axi_coverage)

    uvm_analysis_imp_apb #(apb_seq_item, apb_axi_coverage) apb_export;
    uvm_analysis_imp_axi #(axi_txn,      apb_axi_coverage) axi_export;

    // sampled values
    bit          c_write;
    bit [31:0]   c_addr;
    bit [3:0]    c_strb;
    bit          c_slverr;
    int unsigned c_wait;
    int unsigned c_idle;

    bit          a_write;
    bit [1:0]    a_resp;

    covergroup cg_apb;
        option.per_instance = 1;

        cp_dir: coverpoint c_write {
            bins read  = {0};
            bins write = {1};
        }
        cp_addr_region: coverpoint c_addr {
            bins low  = {[32'h0000_0000 : 32'h0000_0FFF]};
            bins mid  = {[32'h0000_1000 : 32'h0000_FFFF]};
            bins high = {[32'h0001_0000 : 32'hFFFF_FFFF]};
        }
        cp_strb: coverpoint c_strb iff (c_write) {
            bins full    = {4'hF};
            bins none    = {4'h0};
            bins partial = {[4'h1 : 4'hE]};
        }
        cp_slverr: coverpoint c_slverr {
            bins ok    = {0};
            bins error = {1};
        }
        cp_wait: coverpoint c_wait {
            bins short_w  = {[0:2]};
            bins medium_w = {[3:6]};
            bins long_w   = {[7:15]};
            bins huge_w   = {[16:$]};
        }
        cp_idle: coverpoint c_idle {
            bins back_to_back = {0};
            bins short_gap    = {[1:3]};
            bins long_gap     = {[4:$]};
        }

        cx_dir_err:  cross cp_dir, cp_slverr;
        cx_dir_idle: cross cp_dir, cp_idle;
        cx_dir_addr: cross cp_dir, cp_addr_region;
    endgroup

    covergroup cg_axi;
        option.per_instance = 1;

        cp_axi_dir: coverpoint a_write {
            bins read  = {0};
            bins write = {1};
        }
        cp_axi_resp: coverpoint a_resp {
            bins okay   = {2'b00};
            bins slverr = {2'b10};
            bins decerr = {2'b11};
            ignore_bins exokay = {2'b01}; // not generated by an AXI4-Lite slave
        }
        cx_axi_dir_resp: cross cp_axi_dir, cp_axi_resp;
    endgroup

    function new(string name, uvm_component parent);
        super.new(name, parent);
        apb_export = new("apb_export", this);
        axi_export = new("axi_export", this);
        cg_apb = new();
        cg_axi = new();
    endfunction

    function void write_apb(apb_seq_item t);
        c_write  = t.write;
        c_addr   = t.addr;
        c_strb   = t.strb;
        c_slverr = t.slverr;
        c_wait   = t.wait_states;
        c_idle   = t.idle_cycles;
        cg_apb.sample();
    endfunction

    function void write_axi(axi_txn t);
        a_write = t.write;
        a_resp  = t.resp;
        cg_axi.sample();
    endfunction

    function void report_phase(uvm_phase phase);
        super.report_phase(phase);
        `uvm_info("COV_SUMMARY",
            $sformatf("APB coverage: %0.1f%%   AXI coverage: %0.1f%%",
                      cg_apb.get_coverage(), cg_axi.get_coverage()),
            UVM_LOW)
    endfunction

endclass : apb_axi_coverage
